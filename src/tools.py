@tool
def find_optimal_parameter(
    sweeping_parameter: Annotated[str, "Name of the sweeping parameter, e.g. 'ecutwfc', 'kspacing', and etc."],
    filename_w_ref: Annotated[
        List[Tuple[str, str]],
        "List of (filename, source_result_id) pairs. Each filename is the output file corresponding to one swept setting; the ref is the source_result_id of the previous tool output where that specific filename was generated. Aligned by index with `parameters_w_ref`.",
    ],
    parameters_w_ref: Annotated[
        List[Tuple[float, str]],
        "List of (parameter_value, source_result_id) pairs. Each parameter_value is the swept value used in the corresponding filename. Aligned by index with `filename_w_ref`.",
    ],
    reference_file: Annotated[str, "Among the list of files, the reference_file filename corresponding to the most expensive / most accurate reference calculation."],
    threshold: Annotated[float, "Maximum allowed absolute energy difference in eV from the reference energy."],
    reasons: Annotated[
        Dict[str, str],
        "Per-parameter rationale. For each parameter, write 2-4 sentences "
        "covering: "
        "(a) WHICH STUDY OR EXPLORATION this tool call is part of (e.g. "
        "'convergence test for ecutwfc', 'production run for adsorption "
        "energy', 'sensitivity sweep over n_fixed_layers', 'one-off check'); "
        "(b) THE ROLE THIS PARAMETER plays in that study (e.g. 'being varied "
        "now', 'fixed at converged value from prior convergence test', "
        "'inherited from upstream tool', 'placeholder before a real value "
        "is obtained'); "
        "(c) WHY THIS SPECIFIC VALUE: how it was chosen, what evidence "
        "supports it, and the expected effect on the output. "
        "The keys must include: 'threshold'.",
    ],
) -> Dict[str, Any]:
    """
    Find the most optimal value of ONE specific parameter for production run.
    Use this when all OTHER parameters are already set at their most accurate
    settings, and you want to find the cheapest setting of `sweeping_parameter`
    that still matches the reference within `threshold`. Run this once per
    parameter you want to optimize.

    `filename_w_ref` and `parameters_w_ref` must have equal length and be
    aligned by index: entry i is `(filename_i, ref_id_a)` and `(parameter_i,
    ref_id_b)`. The two ref IDs at the same index may or may not be equal.

    reference_id in the output ties with: the most optimal parameter value for production run, float
    """
    WORKING_DIRECTORY = var.my_WORKING_DIRECTORY

    if len(filename_w_ref) != len(parameters_w_ref):
        raise ValueError(
            "filename_w_ref and parameters_w_ref must have the same length."
        )

    bare_filenames: List[str] = []
    bare_filename_refs: List[str] = []
    bare_parameters: List[float] = []
    bare_parameter_refs: List[str] = []

    for (fname, fname_ref), (pval, pval_ref) in zip(filename_w_ref, parameters_w_ref):
        ok, msg = CANVAS.verify_artifact(fname, fname_ref)
        if not ok:
            raise ValueError(f"Verification failed for filename {fname}: {msg}")
        ok, msg = CANVAS.verify_artifact(pval, pval_ref)
        if not ok:
            raise ValueError(f"Verification failed for parameter {pval}: {msg}")
        bare_filenames.append(fname)
        bare_filename_refs.append(fname_ref)
        bare_parameters.append(float(pval))
        bare_parameter_refs.append(pval_ref)

    # Add .pwo to all file names if not already.
    Filename_n_parameters: List[Tuple[str, float]] = []
    for fname, pval in zip(bare_filenames, bare_parameters):
        if not fname.endswith('.pwo'):
            fname = fname + '.pwo'
        Filename_n_parameters.append((fname, pval))

    if not reference_file.endswith('.pwo'):
        reference_file += '.pwo'

    file_to_param = dict(Filename_n_parameters)

    if reference_file not in file_to_param:
        raise ValueError(
            f"reference_file '{reference_file}' is not present in the supplied filenames."
        )

    reference_param = file_to_param[reference_file]
    reference_energy = read(os.path.join(WORKING_DIRECTORY, reference_file)).get_potential_energy()

    acceptable: List[Tuple[str, float]] = []
    for filename, param_value in Filename_n_parameters:
        energy = read(os.path.join(WORKING_DIRECTORY, filename)).get_potential_energy()
        if abs(energy - reference_energy) <= threshold:
            acceptable.append((filename, param_value))

    if len(acceptable) == 1:
        return "Only the reference file is within threshold. No acceptable cheaper setting found. Please consider increasing the calculation settings to increase the accuracy of the calculation."

    chosen = max(acceptable, key=lambda x: abs(x[1] - reference_param))

    param_sources: Dict[str, Any] = {
        "filename": bare_filename_refs,
        "parameters": bare_parameter_refs,
    }
    parent_result_ids = list(set(bare_filename_refs + bare_parameter_refs))

    id = CANVAS.register_tool_output(
        tool_name="find_optimal_parameter",
        args={
            "sweeping_parameter": sweeping_parameter,
            "filename": bare_filenames,
            "parameters": bare_parameters,
            "reference_file": reference_file,
            "threshold": threshold,
        },
        value=chosen[1],
        description=f"The most optimal parameter value for production run based on the reference file {reference_file} and the threshold {threshold}. The chosen parameter value is {chosen[1]} with file name {chosen[0]}",
        reasons=reasons,
        parent_result_ids=parent_result_ids,
        parent_result_ids_w_args=param_sources,
        metadata={},
    )

    return f"Please choose {sweeping_parameter}={chosen[1]}. result_ID={id}."


@tool
def calculate_formation_E(
    slabFilePath_w_ref: Annotated[
        Tuple[str, str],
        "(slab calculation file name, source_result_id) pair. "
        "value at index 0 is the file name; value at index 1 is the ref.",
    ],
    adsorbateFilePath_w_ref: Annotated[
        Tuple[str, str],
        "(adsorbate calculation file name, source_result_id) pair.",
    ],
    systemFilePath_w_ref: Annotated[
        Tuple[str, str],
        "(slab-with-adsorbate calculation file name, source_result_id) pair.",
    ],
    reasons: Annotated[
        Dict[str, str],
        "Per-parameter rationale. For each parameter, write 2-4 sentences "
        "covering: "
        "(a) WHICH STUDY OR EXPLORATION this tool call is part of (e.g. "
        "'convergence test for ecutwfc', 'production run for adsorption "
        "energy', 'sensitivity sweep over n_fixed_layers', 'one-off check'); "
        "(b) THE ROLE THIS PARAMETER plays in that study (e.g. 'being varied "
        "now', 'fixed at converged value from prior convergence test', "
        "'inherited from upstream tool', 'placeholder before a real value "
        "is obtained'); "
        "(c) WHY THIS SPECIFIC VALUE: how it was chosen, what evidence "
        "supports it, and the expected effect on the output. "
        "The keys must include: 'slabFilePath', 'adsorbateFilePath', "
        "'systemFilePath'.",
    ],
):
    """Using the energies of the slab, adsorbate, and slab-with-adsorbate,
    calculate the formation energy of the adsorbate on the slab.
    Be careful that all calculations must be done with the same parameter settings
    for energies to be comparable.

    All three filename arguments require a source_result_id; the formation
    energy is a high-stakes value and provenance is mandatory.

    reference_id in the output ties with: the formation energy of the adsorbate on the slab, float
    """
    slabFilePath, slabFilePath_ref = slabFilePath_w_ref
    adsorbateFilePath, adsorbateFilePath_ref = adsorbateFilePath_w_ref
    systemFilePath, systemFilePath_ref = systemFilePath_w_ref

    # Verify each filename against its declared source.
    for fname, ref, label in (
        (slabFilePath, slabFilePath_ref, "slabFilePath"),
        (adsorbateFilePath, adsorbateFilePath_ref, "adsorbateFilePath"),
        (systemFilePath, systemFilePath_ref, "systemFilePath"),
    ):
        ok, msg = CANVAS.verify_artifact(fname, ref)
        if not ok:
            return f"Verification failed for {label}={fname!r} with ref {ref!r}: {msg}"

    working_directory = var.my_WORKING_DIRECTORY
    if not slabFilePath.endswith('.pwo'):
        slabFilePathFull = os.path.join(working_directory, slabFilePath + '.pwo')
    else:
        slabFilePathFull = os.path.join(working_directory, slabFilePath)
    if not adsorbateFilePath.endswith('.pwo'):
        adsorbateFilePathFull = os.path.join(working_directory, adsorbateFilePath + '.pwo')
    else:
        adsorbateFilePathFull = os.path.join(working_directory, adsorbateFilePath)
    if not systemFilePath.endswith('.pwo'):
        systemFilePathFull = os.path.join(working_directory, systemFilePath + '.pwo')
    else:
        systemFilePathFull = os.path.join(working_directory, systemFilePath)

    slab = read(slabFilePathFull)
    adsorbate = read(adsorbateFilePathFull)
    system = read(systemFilePathFull)

    slabEnergy = slab.get_potential_energy() / len(slab)
    adsorbateEnergy = adsorbate.get_potential_energy()
    systemEnergy = system.get_potential_energy()

    slabSpecies = slab.numbers[0]
    NslabInSystem = system.numbers.tolist().count(slabSpecies)

    formationEnergy = systemEnergy - slabEnergy * NslabInSystem - adsorbateEnergy

    param_sources: Dict[str, Any] = {
        "slabFilePath": slabFilePath_ref,
        "adsorbateFilePath": adsorbateFilePath_ref,
        "systemFilePath": systemFilePath_ref,
    }
    parent_result_ids = list({slabFilePath_ref, adsorbateFilePath_ref, systemFilePath_ref})

    id = CANVAS.register_tool_output(
        tool_name="calculate_formation_E",
        args={
            "slabFilePath": slabFilePath,
            "adsorbateFilePath": adsorbateFilePath,
            "systemFilePath": systemFilePath,
        },
        value=formationEnergy,
        description=(
            f"The formation energy of the adsorbate on the slab calculated "
            f"using {slabFilePath}, {adsorbateFilePath}, and {systemFilePath}"
        ),
        reasons=reasons,
        parent_result_ids=parent_result_ids,
        parent_result_ids_w_args=param_sources,
        metadata={},
    )

    return f"The formation energy of the adsorbate on the slab is {formationEnergy} eV. Energy_ID={id}."


