def _dbg(msg: str) -> None:
    """Print a debug message and sleep so logs are easy to follow live."""
    sleep_time = min(6, max(1, int(len(f"[DBG] {msg}") * 0.01 * _DBG_SLEEP)))
    outStr = f"[DBG][{sleep_time}] {msg}"
    print(outStr, flush=True)
