def extract_text_from_tool_output(
    reasons: Annotated[
        str,
        "Per-parameter rationale. Write 2-3 sentences covering: "
        "(a) THE ROLE this extracted text plays in the study described in "
        "`context` (e.g. 'used as input filename for a downstream tool', "
        "'recorded as the calculation status note', 'identifies the "
        "converged structure for the next stage'); "
        "(b) WHY THIS SPECIFIC SOURCE AND SNIPPET: how the source tool "
        "output was chosen, why the snippet is the right region of the "
        "output, and what the expected interpretation of the text is. "
        "For an extraction step, treat the extraction itself as the "
        "'parameter': one combined rationale, not per-key entries.",
    ],
    source_tool_call_id: Annotated[
        str,
        "The result_id of the text result from a prior tool call that you "
        "want to extract a textual span from.",
    ],
    text: Annotated[
        str,
        "The textual span you want to verify and extract from the tool "
        "output. Must appear verbatim in the source. Do NOT use this tool "
        "for numeric values — use extract_numeric_from_tool_output instead.",
    ],
    evidence_snippet: Annotated[
        str,
        "A substring from the tool output that contains `text`, used to "
        "disambiguate when `text` may appear in multiple regions of the "
        "source.",
    ],
    description: Annotated[
        str,
        "A brief description of what this text represents (e.g. 'the "
        "converged total energy line', 'the chemical formula of the relaxed "
        "structure', 'the warning message about k-point sampling').",
    ],
    context: Annotated[
        str,
        "1-2 sentences describing which study or exploration this tool call "
        "is part of, and the reason for the call. You MUST state EXPLICITLY "
        "whether this is a 'production run' (its output feeds a reported final "
        "result) or a 'sub-study / exploration' (e.g. 'convergence test for "
        "ecutwfc', 'sensitivity sweep over n_fixed_layers', 'one-off check'). "
        "This production-vs-sub-study declaration is taken at face value by the "
        "reviewer and sets the provenance requirements, so state it accurately."
    ],
):
    """
    Verify that a textual span was explicitly present in the raw output of a
    prior tool call, then register it as a trusted text artifact and return
    a result_id.

    This tool is for TEXT only. If the agent tries to extract something that
    is actually a numeric value (e.g. "3.92" as a string), the tool refuses
    and points the agent to extract_numeric_from_tool_output. This prevents
    laundering numeric provenance through the text path.

    reference_id ties with: verified extracted text, str
    """
    # Reject numeric-shaped strings — they belong to the numeric extractor.
    stripped = text.strip()
    if stripped:
        try:
            float(stripped)
            return (
                "EXTRACTION_FAILED: the extracted text is numeric-shaped "
                f"({text!r}). Use extract_numeric_from_tool_output instead. "
                "The text extractor must not be used to launder numeric "
                "values through the text path."
            )
        except ValueError:
            pass  # not numeric — good, continue.

    if not stripped:
        return (
            "EXTRACTION_FAILED: extracted text is empty or whitespace-only. "
            "Provide a non-empty span."
        )

    record = CANVAS.get_artifact(source_tool_call_id)
    if record is None:
        return (
            f"EXTRACTION_FAILED: source_tool_call_id='{source_tool_call_id}' "
            "was not found in the tool output registry. Please check the "
            "canvas and try again, or regenerate the source result with the "
            "corresponding tool."
        )

    raw_text = record.value
    if not isinstance(raw_text, str):
        # The text extractor can only operate on string-valued source artifacts.
        return (
            f"EXTRACTION_FAILED: source artifact value is not text "
            f"(got {type(raw_text).__name__}). The text extractor requires "
            "a string-valued source."
        )

    # Find candidate snippet regions in the source.
    snippet_spans = util_find_all_substring_spans(raw_text, evidence_snippet)
    if not snippet_spans:
        return (
            "EXTRACTION_FAILED: evidence_snippet was not found in the recorded "
            f"tool output. tool_call_id='{source_tool_call_id}'"
        )

    # The extracted text must appear inside at least one snippet region.
    matching_spans: List[Tuple[int, int]] = []
    for s0, s1 in snippet_spans:
        if text in raw_text[s0:s1]:
            matching_spans.append((s0, s1))

    if not matching_spans:
        return (
            "EXTRACTION_FAILED: the requested text was not found inside any "
            "region matching the evidence_snippet. Ensure the snippet you "
            "supply actually contains the text you are extracting. "
            f"tool_call_id='{source_tool_call_id}'"
        )

    # Disambiguation: if the snippet itself appears in multiple regions of
    # the source AND each region contains the text, the snippet is too weak.
    # Surface the candidate regions so the agent can refine.
    if len(matching_spans) > 1:
        preview = []
        for s0, s1 in matching_spans[:10]:
            ctx_start = max(0, s0 - 20)
            ctx_end = min(len(raw_text), s1 + 20)
            preview.append({
                "snippet_span": [s0, s1],
                "context": raw_text[ctx_start:ctx_end],
            })
        return (
            "EXTRACTION_FAILED: the evidence_snippet matches multiple regions "
            "of the source, each of which contains the requested text. "
            "Please refine your evidence_snippet to disambiguate which "
            "occurrence you mean. "
            f"Candidates: {preview}"
        )

    s0, s1 = matching_spans[0]

    # Locate the exact text span inside the chosen snippet region for the
    # provenance record.
    rel = raw_text[s0:s1].index(text)
    text_start = s0 + rel
    text_end = text_start + len(text)
    matched_text = raw_text[text_start:text_end]  # equal to `text` by construction

    merged_reasons = _merge_context(context, reasons)

    # ---- Call-time guard (point 6): text is now mechanically verified to be
    # present and unique in the source. Guard value-correctness and
    # source-appropriateness BEFORE registering. ----
    _dbg(f"[PT6 extract-guard:text] text={text[:60]!r} from "
         f"source={getattr(record, 'tool_name', '')!r}; calling on-site guard ...")
    _gv, _gr = guard_extraction(
        source_description=getattr(record, "description", "") or "",
        source_tool=getattr(record, "tool_name", "") or "",
        source_args=getattr(record, "args", {}) or {},
        source_text=raw_text,
        extracted_value=text,
        extraction_rationale=merged_reasons,
    )
    _dbg(f"[PT6 extract-guard:text] verdict={_gv}"
         f"{(' reason=' + repr(_gr[:120])) if _gr else ''}")
    if _gv == "fail":
        _dbg("[PT6 extract-guard:text] FAIL -> text NOT registered (hard block).")
        return (
            "EXTRACTION_GUARD_FAILED: the on-site guard rejected this "
            f"extraction. Reason: {_gr}\nThe text was NOT registered. Check "
            "that you are extracting from the correct source (not a test / "
            "scratch / stale run) and that the span matches its stated "
            "purpose, then try again."
        )

    _md = {
        "matched_text": matched_text,
        "matched_span": [text_start, text_end],
        "evidence_snippet_span": [s0, s1],
    }
    if _gv == "warning":
        _dbg("[PT6 extract-guard:text] WARNING -> registering with metadata stamp.")
        _md["guard_verdict"] = "warning"
        _md["guard_reasoning"] = _gr

    result_id = CANVAS.register_tool_output(
        tool_name="extract_text_from_tool_output",
        args={
            "source_tool_call_id": source_tool_call_id,
            "text": text,
            "evidence_snippet": evidence_snippet,
            "description": description,
        },
        value=text,
        description=description,
        context=context,
        reasons=merged_reasons,
        parent_result_ids=[source_tool_call_id],
        parent_result_ids_w_args={"source_tool_call_id": source_tool_call_id},
        metadata=_md,
    )

    return f"text: {text!r} is now registered with id {result_id} and can be used for further calculations."



