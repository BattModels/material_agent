@tool
def read_energy_from_output(
    reasons: Annotated[
        Dict[str, str],
        "Per-parameter rationale — ONE entry per key listed below. For EACH "
        "parameter write 2-3 SPECIFIC sentences covering: "
        "(a) ROLE: the part this parameter plays in the study named in `context` "
        "(e.g. 'being varied now', 'fixed at the value converged in <name the "
        "study / result_id>', 'inherited from an upstream tool output', 'held by "
        "design while a sub-study runs'); "
        "(b) WHY THIS VALUE: how it was chosen and the evidence for it. If it "
        "comes from an upstream result, NAME that result and confirm it was "
        "characterized under the SAME conditions this call uses; if it is a "
        "deliberate design choice, give the physical justification. Generic "
        "phrases such as 'standard value' or 'typical setting' with no study-"
        "specific reason are NOT acceptable. Your `context` is automatically "
        "prepended to every rationale, so it is read together with what you write. "
        "The keys must include: 'jobFilenames'.",
    ],
    jobFilenames_w_ref: Annotated[
        List[Tuple[str, str]],
        "List of (filename, filename_ref_id) pairs. Energy of <filename> will be read and printed, filename_ref_id is the source_result_id of the previous tool output where that specific filename was generated. Each filename_ref_id accepts an 8-char id to reference the output, or `<8-char-id>.<param_name>` to reference an input parameter of a past tool call (see `list_referenceable_inputs`)."
    ],
    context: Annotated[
        str,
        "1-2 sentences describing which study or exploration this tool call "
        "is part of, and the reason for the call. You MUST state EXPLICITLY "
        "whether this is a 'production run' (its output feeds a reported final "
        "result) or a 'sub-study / exploration' (e.g. 'convergence test for "
        "ecutwfc', 'sensitivity sweep over n_fixed_layers', 'one-off check'). "
        "This production-vs-sub-study declaration is taken at face value by the "
        "reviewer and sets the provenance requirements, so state it accurately."
    ],
) -> str:
    '''Read the total energy from the output file in job list and return it in a string
    reference_id in the output ties with: the energy read from the output file, float'''

    assert isinstance(jobFilenames_w_ref, list), "jobFilenames_w_ref should be a list"
    for name, ref in jobFilenames_w_ref:
        assert isinstance(name, str), "filename should be a string"
        assert isinstance(ref, str), "filename_ref_id should be a string"

    WORKING_DIRECTORY = var.my_WORKING_DIRECTORY

    bare_filenames: List[str] = []
    bare_refs: List[str] = []
    for name, ref in jobFilenames_w_ref:
        ok, msg = CANVAS.verify_artifact(name, ref)
        if not ok:
            return f"Verification failed for job filename {name} with reference ID {ref}: {msg}"
        bare_filenames.append(name)
        bare_refs.append(ref)

    print(f"actual job list: {bare_filenames}")

    merged_reasons = _merge_context(context, reasons)

    result = ""
    for job, ref in zip(bare_filenames, bare_refs):
        output_file = job
        if not job.endswith('.pwo'):
            output_file += '.pwo'
        file_path = os.path.join(WORKING_DIRECTORY, output_file)
        if not os.path.exists(file_path):
            return f"Output file {output_file} does not exist, please check the job list"
        try:
            atoms = read(file_path)
        except:
            try:
                with open(file_path, 'r') as f:
                    lines = f.readlines()
                notConverge = False
                for line in lines:
                    if "convergence NOT achieved" in line:
                        notConverge = True
                        result += f"Job {job} did not converge\n"
                        break
                if not notConverge:
                    return f"Invalid output file {output_file} or calculation failed, please submit the {job} again."
            except:
                return f"Invalid output file {output_file} or calculation failed, please submit the {job} again."
            continue

        # Per-job artifact: each gets its own param_sources (single-element).
        id = CANVAS.register_tool_output(
            tool_name="read_energy_from_output",
            args={"jobFilename": job},
            value=atoms.get_potential_energy(),
            description=f"The energy read from {job} is {atoms.get_potential_energy()} eV. The tool automatically append .pwo to the all filenames to read the output files.",
            context=context,
        reasons=merged_reasons,
            parent_result_ids=[ref],
            parent_result_ids_w_args={"jobFilename": ref},
            metadata={},
        )

        result += f"Energy read from {job} is {atoms.get_potential_energy()} eV. Energy reference_ID={id}\n"
        time.sleep(1)
    print(result)

    return result