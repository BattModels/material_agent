def analyze_BEEF_result(
    reasons: Annotated[
        Dict[str, str],
        "Per-parameter rationale — ONE entry per key listed below. For EACH "
        "parameter write 2-3 SPECIFIC sentences covering: "
        "(a) ROLE: the part this parameter plays in the study named in `context` "
        "(e.g. 'being varied now', 'fixed at the value converged in <name the "
        "study / result_id>', 'inherited from an upstream tool output', 'held by "
        "design while a sub-study runs'); "
        "(b) WHY THIS VALUE: how it was chosen and the evidence for it. If it "
        "comes from an upstream result, NAME that result and confirm it was "
        "characterized under the SAME conditions this call uses; if it is a "
        "deliberate design choice, give the physical justification. Generic "
        "phrases such as 'standard value' or 'typical setting' with no study-"
        "specific reason are NOT acceptable. Your `context` is automatically "
        "prepended to every rationale, so it is read together with what you write. "
        "The keys must include: 'slabFilePath', 'adsorbateFilePath', "
        "'systemFilePath'.",
    ],
    slabFilePath_w_ref: Annotated[
        Tuple[str, str],
        "(slab calculation file, source_result_id) pair. value at index 0 is "
        "the file path; value at index 1 is the ref. The source_result_id "
        "accepts an 8-char id to reference the output, or `<8-char-id>.<param_name>` to reference "
        "an input parameter of a past tool call (see "
        "`list_referenceable_inputs`).",
    ],
    adsorbateFilePath_w_ref: Annotated[
        Tuple[str, str],
        "(adsorbate calculation file, source_result_id) pair. The "
        "source_result_id accepts an 8-char id to reference the output, or "
        "`<8-char-id>.<param_name>` to reference an input parameter of a "
        "past tool call (see `list_referenceable_inputs`).",
    ],
    systemFilePath_w_ref: Annotated[
        Tuple[str, str],
        "(slab-with-ontop-adsorbate calculation file, source_result_id) pair. "
        "The source_result_id accepts an 8-char id to reference the output, or "
        "`<8-char-id>.<param_name>` to reference an input parameter of a "
        "past tool call (see `list_referenceable_inputs`).",
    ],
    context: Annotated[
        str,
        "1-2 sentences describing which study or exploration this tool call "
        "is part of, and the reason for the call. You MUST state EXPLICITLY "
        "whether this is a 'production run' (its output feeds a reported final "
        "result) or a 'sub-study / exploration' (e.g. 'convergence test for "
        "ecutwfc', 'sensitivity sweep over n_fixed_layers', 'one-off check'). "
        "This production-vs-sub-study declaration is taken at face value by the "
        "reviewer and sets the provenance requirements, so state it accurately."
    ],
) -> str:
    '''Read, extract, and analyze BEEF calculation results for slab,
    adsorbate, and surface-with-adsorbate. Return the mean and standard
    deviation of the adsorption energy. Be careful that all calculations
    must be done with the same parameter settings for energies to be comparable.

    Every one of the three inputs MUST be a BEEF-vdW ENSEMBLE calculation (each
    produces an ensemble of energies); the reported standard deviation comes from
    that ensemble. Plain single-functional SCF/relax outputs contain no ensemble and
    cannot yield an uncertainty — supplying non-ensemble outputs here is invalid.

    All three filename arguments require a source_result_id; the BEEF
    ensemble values are high-stakes and provenance is mandatory.

    reference_id in the output ties with: the mean adsorption energy from the BEEF ensemble,
    float; the standard deviation of adsorption energy from the BEEF ensemble,
    float.
    '''
    slabFilePath, slabFilePath_ref = slabFilePath_w_ref
    adsorbateFilePath, adsorbateFilePath_ref = adsorbateFilePath_w_ref
    systemFilePath, systemFilePath_ref = systemFilePath_w_ref

    # Verify each filename against its declared source.
    for fname, ref, label in (
        (slabFilePath, slabFilePath_ref, "slabFilePath"),
        (adsorbateFilePath, adsorbateFilePath_ref, "adsorbateFilePath"),
        (systemFilePath, systemFilePath_ref, "systemFilePath"),
    ):
        ok, msg = CANVAS.verify_artifact(fname, ref)
        if not ok:
            return f"Verification failed for {label}={fname!r} with ref {ref!r}: {msg}"

    WORKING_DIRECTORY = var.my_WORKING_DIRECTORY
    DirOfInterests = WORKING_DIRECTORY.split('/')[-1]

    PathList = [slabFilePath, adsorbateFilePath, systemFilePath]

    for i in range(len(PathList)):
        tmp = PathList[i]
        try:
            if (not PathList[i].startswith(DirOfInterests)
                    and not PathList[i].startswith(f'./{DirOfInterests}')
                    and not PathList[i].startswith('/nfs')):
                if not PathList[i].endswith('.pwo'):
                    PathList[i] += '.pwo'
                PathList[i] = os.path.join(WORKING_DIRECTORY, PathList[i])
            _ = read(PathList[i])
        except:
            if os.path.exists(PathList[i]):
                return f"{tmp} did not finish successfully."
            return (
                f"Invalid input atoms directory: {tmp}. Make sure to supply "
                f"either an absolute path, or a relative path starting with "
                f"'./{DirOfInterests}'. Please check the path in canvas and "
                f"try again."
            )

    # Read BEEF energies.
    slab_e = read_BEEF_output(PathList[0])
    if slab_e == "WrongCalc":
        return "Please run slab ensemble calculation using BEEF-vdW with relaxed slab structure! Do not proceed any further!"
    adsorbate_e = read_BEEF_output(PathList[1])
    if adsorbate_e == "WrongCalc":
        return "Please run adsorbate ensemble calculation using BEEF-vdW with relaxed adsorbate structure! Do not proceed any further!"
    system_e = read_BEEF_output(PathList[2])
    if system_e == "WrongCalc":
        return "Please run surface-with-adsorbate ensemble calculation using BEEF-vdW with relaxed slab and adsorbate structure! Do not proceed any further!"

    # Plot.
    try:
        energy_dict = {'clean': slab_e, 'CO': adsorbate_e, 'system': system_e}

        fontsize = 15
        plot_settings = {
            "axes.labelsize": fontsize, "axes.labelweight": "bold",
            "xtick.labelsize": fontsize, "ytick.labelsize": fontsize,
            "xtick.major.size": 7, "ytick.major.size": 7,
            "xtick.major.width": 2.0, "ytick.major.width": 2.0,
            "xtick.direction": "in", "ytick.direction": "in",
            "font.size": fontsize, "axes.linewidth": 2.0,
            "lines.dashed_pattern": [5, 2.5], "lines.markersize": 10,
            "lines.linewidth": 2, "lines.markeredgewidth": 1,
            "legend.fontsize": fontsize, "legend.frameon": False,
            'figure.figsize': [6, 6],
        }
        rcParams.update(plot_settings)

        df = pd.DataFrame(energy_dict)
        df.to_csv('energies.csv', index=False)
        ads_E = df['system'] - df['clean'] - df['CO']
        fig = plt.figure(figsize=(6, 5))
        ax = fig.add_axes([0, 0, 1, 1])
        ax.hist(ads_E, bins=50, color='blue', alpha=0.7, label='E distribution')
        ax.axvline(ads_E.mean(), color='k', linestyle=':', linewidth=2, label='E mean')
        plt.xlabel('Adsorption Energy (eV)')
        plt.ylabel('Frequency')
        plt.savefig('energy_distribution.png', dpi=300, bbox_inches='tight')
    except:
        print("Failed to plot the energy distribution.")

    # Formation.
    E_formation = system_e - slab_e - adsorbate_e
    E_formation_mean = E_formation.mean()
    E_formation_std = E_formation.std()

    common_args = {
        "slabFilePath": slabFilePath,
        "adsorbateFilePath": adsorbateFilePath,
        "systemFilePath": systemFilePath,
    }
    param_sources: Dict[str, Any] = {
        "slabFilePath": slabFilePath_ref,
        "adsorbateFilePath": adsorbateFilePath_ref,
        "systemFilePath": systemFilePath_ref,
    }
    parent_result_ids = list({slabFilePath_ref, adsorbateFilePath_ref, systemFilePath_ref})

    merged_reasons = _merge_context(context, reasons)

    _desc = (
        f"BEEF-vdW ensemble adsorption-energy analysis using {slabFilePath}, "
        f"{adsorbateFilePath}, and {systemFilePath}.")
    _pblock, _pmd = _param_gate(
        "analyze_BEEF_result", common_args, merged_reasons, context, _desc,
        param_sources=param_sources, parent_result_ids=parent_result_ids,
        value=E_formation_mean, varied_parameters=[],
    )
    if _pblock:
        return _pblock
    _block, _md = _cross_param_gate(
        "analyze_BEEF_result", common_args, merged_reasons, context, _desc)
    if _block:
        return _block
    _md = {**_pmd, **_md}

    mean_id = CANVAS.register_tool_output(
        tool_name="analyze_BEEF_result",
        args=common_args,
        value=E_formation_mean,
        description=(
            f"The mean adsorption energy calculated using {slabFilePath}, "
            f"{adsorbateFilePath}, and {systemFilePath}"
            f"The tool automatically append .pwo to the all filenames to read the output files."
        ),
        context=context,
        reasons=merged_reasons,
        parent_result_ids=parent_result_ids,
        parent_result_ids_w_args=param_sources,
        metadata=_md,
    )

    std_id = CANVAS.register_tool_output(
        tool_name="analyze_BEEF_result",
        args=common_args,
        value=E_formation_std,
        description=(
            f"The standard deviation of adsorption energy calculated using "
            f"{slabFilePath}, {adsorbateFilePath}, and {systemFilePath}"
            f"The tool automatically append .pwo to the all filenames to read the output files."
        ),
        context=context,
        reasons=merged_reasons,
        parent_result_ids=parent_result_ids,
        parent_result_ids_w_args=param_sources,
        metadata=_md,
    )

    return (
        f"The mean adsorption energy is {E_formation_mean} eV, and the "
        f"standard deviation is {E_formation_std} eV. Mean_ID={mean_id}, "
        f"Std_ID={std_id}."
    )


