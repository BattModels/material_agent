def _merge_context(context: str, reasons: Any) -> Dict[str, str]:
    """Prepend the per-call `context` onto each per-parameter rationale.

    Accepts `reasons` in either of two shapes:
      * `Dict[str, str]` — multi-key rationale, one entry per tool parameter.
      * `str`            — single rationale used by tools with one logical input.

    In both cases, the return value is a dict so that every artifact registered
    via `register_tool_output(reasons=...)` has a uniform shape on disk. For
    str-shape inputs, the merged value is stored under the key `"reasons"`,
    matching the pre-existing convention used by tools like
    `math_expression_tool` and `extract_numeric_from_tool_output`.

    Empty / whitespace-only `context` is rejected at the tool boundary so that
    a missing study description fails loudly instead of silently degrading the
    verifier's signal.
    """
    if not context or not context.strip():
        raise ValueError(
            "context is required and must be non-empty. Describe in one "
            "sentence which study or exploration this tool call is part of "
            "(e.g. 'convergence test for ecutwfc', 'production run for "
            "adsorption energy', 'sensitivity sweep over n_fixed_layers', "
            "'one-off check')."
        )
    prefix = f"Context: {context.strip()}"
    if isinstance(reasons, dict):
        return {k: f"{prefix}\n\nRationale: {v}" for k, v in reasons.items()}
    return {"reasons": f"{prefix}\n\nRationale: {reasons}"}


def _cross_param_gate(tool_name, args, merged_reasons, context, description):
    """On-site cross-parameter consistency gate, run right before an artifact is
    registered by one of the CROSS_PARAM_TOOLS. Mirrors the guard_math_expression
    consumption pattern. Returns (block_message_or_None, metadata_dict):
      - fail    -> (message, {}): the caller must RETURN the message WITHOUT
                   registering (hard block; the on-site value checks already
                   passed, so this rejects a scientifically-inconsistent set).
      - warning -> (None, {stamp}): register, but stamp the warning in metadata.
      - pass    -> (None, {}): register normally.
    Fails OPEN (pass) inside guard_cross_parameters if the judge is unavailable."""
    _cpv, _cpr = guard_cross_parameters(
        tool_name=tool_name, args=args, reasons=merged_reasons,
        context=context, description=description,
    )
    if _cpv == "fail":
        return (
            f"{tool_name.upper()}_CROSS_PARAM_FAILED: the cross-parameter "
            f"consistency check rejected this call. Reason: {_cpr}\n"
            f"The result was NOT registered. Fix the flagged inconsistency (e.g. "
            f"mutually inconsistent inputs, a wrong reference/baseline, or too few "
            f"points) and call the tool again with corrected parameters/rationale."
        ), {}
    md = {}
    if _cpv == "warning":
        md = {"cross_param_verdict": "warning", "cross_param_reasoning": _cpr}
    return None, md


def _param_gate(tool_name, args, merged_reasons, context, description,
                param_sources=None, parent_result_ids=None, value=None,
                varied_parameters=None):
    """On-site PER-PARAMETER gate (Phase 3), run right before an artifact is
    registered — AFTER the tool's deterministic value checks and BEFORE
    `_cross_param_gate` (sequence: value-check -> per-param -> cross-param ->
    register; proceed iff all pass). Mirrors `_cross_param_gate`'s contract:
      - fail    -> (message, {}): the caller must RETURN the message WITHOUT
                   registering (hard block — STRICT: any per-param fail blocks).
      - warning -> (None, {stamp}): register, but stamp the warning in metadata.
      - pass    -> (None, {}): register normally.
    Fails OPEN (pass) inside guard_parameterization if the judge is unavailable."""
    _pv, _pr = guard_parameterization(
        tool_name=tool_name, args=args, value=value, reasons=merged_reasons,
        param_sources=param_sources, parent_result_ids=parent_result_ids,
        description=description, context=context,
        varied_parameters=varied_parameters,
    )
    if _pv == "fail":
        return (
            f"{tool_name.upper()}_PARAM_GATE_FAILED: the per-parameter check "
            f"rejected this call. Reason: {_pr}\n"
            f"The result was NOT registered. Fix the flagged parameter(s) (e.g. a "
            f"wrong/missing provenance source, a value inconsistent with its "
            f"source, or a non-situated 'standard value' rationale) and call the "
            f"tool again with corrected parameters/rationale."
        ), {}
    md = {}
    if _pv == "warning":
        md = {"param_verdict": "warning", "param_reasoning": _pr}
    return None, md


_ALLOWED_FUNCS = {
    "abs": abs, "round": round, "min": min, "max": max, "sum": sum,
    "pow": pow, "sqrt": math.sqrt, "exp": math.exp, "log": math.log,
    "log10": math.log10, "sin": math.sin, "cos": math.cos, "tan": math.tan,
    "asin": math.asin, "acos": math.acos, "atan": math.atan,
    "mean": lambda *x: sum(x) / len(x),
}

_ALLOWED_NODES = (
    ast.Expression, ast.BinOp, ast.UnaryOp, ast.Call, ast.Name, ast.Load,
    ast.Constant, ast.Add, ast.Sub, ast.Mult, ast.Div, ast.Pow, ast.Mod,
    ast.FloorDiv, ast.UAdd, ast.USub, ast.Tuple, ast.List,
)


def _safe_eval(expr: str, variables: dict[str, float]) -> float:
    tree = ast.parse(expr, mode="eval")

    for node in ast.walk(tree):
        if not isinstance(node, _ALLOWED_NODES):
            raise ValueError(f"Unsupported syntax: {type(node).__name__}")

        if isinstance(node, ast.Call):
            if not isinstance(node.func, ast.Name) or node.func.id not in _ALLOWED_FUNCS:
                raise ValueError(f"Function not allowed: {ast.dump(node.func)}")

        if isinstance(node, ast.Name):
            if node.id not in variables and node.id not in _ALLOWED_FUNCS:
                raise ValueError(f"Unknown variable: {node.id}")

    return float(eval(compile(tree, "<expr>", "eval"), {"__builtins__": {}}, {**_ALLOWED_FUNCS, **variables}))


@tool
def math_expression_tool(
    reasons: Annotated[
        str,
        "Per-parameter rationale. Write 2-3 sentences covering: "
        "(a) THE ROLE this calculation plays in the study described in "
        "`context` (e.g. 'computing an intermediate value used downstream', "
        "'final reported quantity', 'sanity check'); "
        "(b) WHY THIS SPECIFIC EXPRESSION AND VALUES: how the inputs were "
        "chosen, what evidence supports them, and the expected meaning of "
        "the output. Since this tool has only one logical parameter (the "
        "expression+values pair), provide one combined rationale rather "
        "than per-key entries.",
    ],
    values_w_ref: Annotated[
        List[Tuple[float, str]],
        "List of (value, ref_result_id) pairs. They will be mapped in order to "
        "x0, x1, x2, ... When you obtain a value from a tool, you will be "
        "given the ref_result_id; place the (value, ref_result_id) pair here. "
        "Each ref_result_id accepts an 8-char id to reference the output, or "
        "`<8-char-id>.<param_name>` to reference an input parameter of a "
        "past tool call (see `list_referenceable_inputs`).",
    ],
    expression: Annotated[
        str,
        "Math expression using x0, x1, x2, ... Example: '(x0 - x1) / x2' or 'sqrt(x0**2 + x1**2)'",
    ],
    context: Annotated[
        str,
        "1-2 sentences describing which study or exploration this tool call "
        "is part of, and the reason for the call. You MUST state EXPLICITLY "
        "whether this is a 'production run' (its output feeds a reported final "
        "result) or a 'sub-study / exploration' (e.g. 'convergence test for "
        "ecutwfc', 'sensitivity sweep over n_fixed_layers', 'one-off check'). "
        "This production-vs-sub-study declaration is taken at face value by the "
        "reviewer and sets the provenance requirements, so state it accurately."
    ],
) -> str:
    """
    Evaluate a math expression on arbitrary input floats.
    Inputs are mapped by order to x0, x1, x2, ...
    reference_id in the output ties with: computed math result, float
    """
    if not values_w_ref:
        return "No values were provided."

    merged_reasons = _merge_context(context, reasons)

    # Verify each value against its ref.
    for v, ref_id in values_w_ref:
        ok, msg = CANVAS.verify_artifact(v, ref_id)
        if not ok:
            return msg

    bare_values = [float(v) for v, _ in values_w_ref]
    bare_refs = [ref for _, ref in values_w_ref]

    # ---- Call-time guard (point 6): inputs are now provenance-verified;
    # guard against value laundering / physically-meaningless expressions
    # BEFORE registering. Independent on-site LLM check; fails open if the
    # guard infrastructure is unavailable. ----
    _guard_inputs = [
        {"name": f"x{i}", "value": bare_values[i], "ref_result_id": bare_refs[i]}
        for i in range(len(bare_values))
    ]
    _dbg(f"[PT6 math-guard] expr={expression!r} over {len(_guard_inputs)} "
         f"provenance-verified input(s); calling on-site guard ...")
    _gv, _gr = guard_math_expression(
        expression=expression,
        inputs=_guard_inputs,
        context_and_reason=merged_reasons,
    )
    _dbg(f"[PT6 math-guard] verdict={_gv}"
         f"{(' reason=' + repr(_gr[:120])) if _gr else ''}")
    if _gv == "fail":
        _dbg("[PT6 math-guard] FAIL -> value NOT registered (hard block).")
        return (
            "MATH_GUARD_FAILED: this computation was rejected by the on-site "
            f"guard. Reason: {_gr}\nThe result was NOT registered. If you "
            "believe this is a legitimate calculation, re-call with a clearer "
            "`context`/`reasons` explaining the scientific meaning; otherwise "
            "obtain the value through the proper computation."
        )
    if _gv == "warning":
        _dbg("[PT6 math-guard] WARNING -> registering with metadata stamp.")

    variables = {f"x{i}": v for i, v in enumerate(bare_values)}
    mapping = {f"x{i}": ref for i, ref in enumerate(bare_refs)}

    try:
        result = _safe_eval(expression, variables)
        _md = {"mapping": mapping}
        if _gv == "warning":
            _md["guard_verdict"] = "warning"
            _md["guard_reasoning"] = _gr
        result_id = CANVAS.register_tool_output(
            tool_name="math_expression_tool",
            args={
                "values": bare_values,
                "expression": expression,
            },
            value=result,
            description=f"Result of evaluating expression '{expression}' with mapping {mapping}",
            context=context,
        reasons=merged_reasons,
            parent_result_ids=list(set(bare_refs)),
            parent_result_ids_w_args={"values": bare_refs},
            metadata=_md,
        )
        return f"Result: {result}. Result_ID={result_id}."
    except Exception as e:
        return f"Failed to evaluate expression: {e}"


